def build_items() -> list[dict]:
    items = []
    for week in range(1, 27):
        theme = WEEK_THEMES[week]
        for weekday in ("ПН", "СР", "ПТ"):
            body = POSTS[(week, weekday)]
            items.append(
                {
                    "week": week,
                    "weekday": weekday,
                    "default_time": DEFAULT_TIME[weekday],
                    "theme": theme,
                    "kind": "post",
                    "body": body,
                }
            )
        question, options = POLLS[week]
        items.append(
            {
                "week": week,
                "weekday": "ВС",
                "default_time": DEFAULT_TIME["ВС"],
                "theme": theme,
                "kind": "poll",
                "body": None,
                "poll_question": question,
                "poll_options": options,
            }
        )
    return items


def main() -> None:
    items = build_items()
    assert len(items) == 104, len(items)
    assert {i["week"] for i in items} == set(range(1, 27))
    assert sum(1 for i in items if i["kind"] == "poll") == 26

    payload = {"timezone": "Asia/Yerevan", "start_date": "2026-08-17", "items": items}
    raw_json = json.dumps(payload, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    compressed = zlib.compress(raw_json, level=9)
    encoded = base64.b64encode(compressed).decode("ascii")

    # Round-trip sanity check before writing anything.
    check = json.loads(zlib.decompress(base64.b64decode(encoded)).decode("utf-8"))
    assert check == payload

    target = Path(__file__).resolve().parents[1] / "app" / "content" / "era_public_pack.py"
    content = target.read_text(encoding="utf-8")
    marker_start = content.index('_PACK = "')
    marker_end = content.index('"\n', marker_start + len('_PACK = "'))
    new_content = content[:marker_start] + f'_PACK = "{encoded}"' + content[marker_end + 1 :]
    target.write_text(new_content, encoding="utf-8", newline="\n")
    print(f"Wrote {len(encoded)} base64 chars ({len(compressed)} compressed bytes) to {target}")


if __name__ == "__main__":
    main()
