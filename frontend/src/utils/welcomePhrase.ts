const SESSION_KEY = "era.welcome.session";
const PHRASE_HISTORY_KEY = "era.welcome.history";
const CORE_HISTORY_KEY = "era.welcome.cores";

function readHistory(key: string): string[] {
  try { return JSON.parse(localStorage.getItem(key) ?? "[]") as string[]; } catch { return []; }
}

/** 8,640 compatible combinations plus standalone phrases, with local anti-repeat. */
export function welcomePhrase(): string {
  const inSession = sessionStorage.getItem(SESSION_KEY);
  if (inSession) return inSession;
  const phraseHistory = readHistory(PHRASE_HISTORY_KEY).slice(-30);
  const coreHistory = readHistory(CORE_HISTORY_KEY).slice(-10);
  const bag: { phrase: string; core: string }[] = [];
  for (const opener of OPENERS) for (const core of CORES) for (const ending of ENDINGS) {
    const phrase = `${opener} ${core}. ${ending}`;
    if (!phraseHistory.includes(phrase) && !coreHistory.includes(core)) bag.push({ phrase, core });
  }
  for (const phrase of STANDALONE) if (!phraseHistory.includes(phrase)) bag.push({ phrase, core: phrase });
  // Shuffle-bag selection: the candidate pool is filtered before one item is
  // consumed, rather than retrying Math.random until a phrase happens to fit.
  const selected = bag[Math.floor(Math.random() * bag.length)] ?? { phrase: STANDALONE[0], core: STANDALONE[0] };
  sessionStorage.setItem(SESSION_KEY, selected.phrase);
  localStorage.setItem(PHRASE_HISTORY_KEY, JSON.stringify([...phraseHistory, selected.phrase].slice(-30)));
  localStorage.setItem(CORE_HISTORY_KEY, JSON.stringify([...coreHistory, selected.core].slice(-10)));
  return selected.phrase;
}
