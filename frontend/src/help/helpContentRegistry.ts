export function resolveHelpTopic(mode: HelpMode, route: string, explicit?: string): HelpContent {
  if (explicit && helpContentRegistry[explicit]) return helpContentRegistry[explicit];
  if (mode === "admin") {
    if (/era[-_]?pro/i.test(route)) return helpContentRegistry.admin_era_pro;
    if (/^admin\/events\//.test(route)) return helpContentRegistry.admin_event;
    if (/^admin\/projects\//.test(route)) return helpContentRegistry.admin_project;
    return helpContentRegistry.admin;
  }
  if (mode === "leader") return helpContentRegistry.leader;
  if (/^projects\/\d+/.test(route)) return helpContentRegistry.project_detail;
  if (route === "projects") return helpContentRegistry.projects;
  if (/project.*(builder|constructor)|builder/.test(route)) return helpContentRegistry.project_builder;
  if (/^events\/\d+/.test(route)) return helpContentRegistry.event_detail;
  if (route === "events") return helpContentRegistry.events;
  if (/^(tasks|calendar|history)(\/|$)/.test(route)) return helpContentRegistry.activity;
  if (/^users\//.test(route)) return helpContentRegistry.users;
  if (/era[-_]?pro|mentorship/.test(route)) return helpContentRegistry.era_pro;
  if (/^opportunities/.test(route)) return helpContentRegistry.opportunities;
  if (/^referral/.test(route)) return helpContentRegistry.referral;
  if (/^(community|leaderboard)/.test(route)) return helpContentRegistry.community;
  if (route === "profile") return helpContentRegistry.profile;
  if (route === "progress" || /^development/.test(route)) return helpContentRegistry.vector;
  return helpContentRegistry.home;
}

