def faq_category_text(category_id: str) -> str:
    category = FAQ_CATEGORIES[category_id]
    intro = (
        "Если ты только знакомишься с ЭРА — начни отсюда.\n"
        if category_id == "start"
        else ""
    )
    available = any(q in FAQ_DATA for q in category["questions"])
    prompt = (
        "Выбери вопрос:"
        if available
        else "В этой теме пока нет вопросов. Выбери другую тему или напиши нам."
    )
    return f"{category['title']}\n\n{intro}{prompt}"


def faq_message_context(text: str | None) -> dict | None:
    """Identify the rendered source, including clicks on older FAQ messages."""
    if text == FAQ_HOME_TEXT:
        return {"category": None, "question": None, "back": "faq:home"}
    for question_id, item in FAQ_DATA.items():
        if text == item["text"]:
            return {
                "category": item["category"],
                "question": question_id,
                "back": f"faq:cat:{item['category']}",
                "action": item.get("action"),
            }
    for category_id in FAQ_CATEGORIES:
        if text == faq_category_text(category_id):
            return {
                "category": category_id,
                "question": None,
                "back": f"faq:cat:{category_id}",
            }
    return None
