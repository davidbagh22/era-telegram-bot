_lock = Lock()
_queue: deque[int] = deque()
_rng = random.SystemRandom()


def _refill() -> None:
    indexes = list(range(1000))
    _rng.shuffle(indexes)
    _queue.extend(indexes)


def combination_count() -> int:
    return len(_OPENERS) * len(_COMMUNITY_LINES) * len(_BOT_LINES)


def build_general_chat_welcome(names: list[str]) -> str:
    """Return one of 1000 non-repeating welcome combinations per process cycle."""
    if not names:
        names = ["Друзья"]

    with _lock:
        if not _queue:
            _refill()
        index = _queue.popleft()

    opener_index = index // 100
    community_index = (index // 10) % 10
    bot_index = index % 10
    closer = _CLOSERS[index % len(_CLOSERS)]

    people = ", ".join(names)
    return (
        f"{_OPENERS[opener_index]}\n\n"
        f"{people}, Вы теперь часть нашего сообщества.\n\n"
        f"{_COMMUNITY_LINES[community_index]}\n\n"
        f"{_BOT_LINES[bot_index]}\n\n"
        f"{closer}"
    )
